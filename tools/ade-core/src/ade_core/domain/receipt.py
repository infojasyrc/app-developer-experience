"""`.ade/answers.yaml` (ade_receipt 1): what was generated, from which version, with which answers.

Read later by `update`, `doctor` and `sync collect` (analysis §4.5).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, ValidationError

from ade_core.domain.errors import AdeCoreError

RECEIPT_DIR = ".ade"
RECEIPT_FILE = "answers.yaml"


class ReceiptEntry(BaseModel):
    model_config = ConfigDict(extra="allow")

    artifact: str
    version: str
    source: str
    output_dir: str
    parameters: dict[str, Any] = {}
    features: dict[str, str] = {}
    generated_at: str


class Receipt(BaseModel):
    model_config = ConfigDict(extra="allow")

    ade_receipt: Literal[1] = 1
    engine_version: str
    cli_version: str | None = None
    artifacts: list[ReceiptEntry] = []

    def upsert(self, entry: ReceiptEntry) -> None:
        """Replace the entry that owns the same output_dir, or append."""
        self.artifacts = [item for item in self.artifacts if item.output_dir != entry.output_dir] + [entry]


def receipt_path(root: Path) -> Path:
    return Path(root) / RECEIPT_DIR / RECEIPT_FILE


def load_receipt(root: Path) -> Receipt | None:
    path = receipt_path(root)
    if not path.is_file():
        return None
    try:
        return Receipt.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")) or {})
    except (yaml.YAMLError, ValidationError) as exc:
        raise AdeCoreError(f"{path}: invalid receipt: {exc}") from exc


def save_receipt(root: Path, receipt: Receipt) -> Path:
    path = receipt_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by appdevexp (ADE). Commit this file: update, doctor and sync read it.\n"
    body = yaml.safe_dump(receipt.model_dump(mode="json", exclude_none=True), sort_keys=False)
    path.write_text(header + body, encoding="utf-8")
    return path
