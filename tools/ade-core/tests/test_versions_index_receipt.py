import pytest

from ade_core.domain.errors import AdeCoreError, ParameterError
from ade_core.domain.index import ArtifactsIndex
from ade_core.domain.receipt import Receipt, ReceiptEntry, load_receipt, receipt_path, save_receipt
from ade_core.domain.versions import Version, is_at_least, matches, select, split_artifact_spec

VERSIONS = ["0.1.1", "0.2.0", "0.2.3", "0.3.0", "1.0.0", "1.4.2", "2.0.0"]


@pytest.mark.parametrize(
    "spec, expected",
    [
        ("latest", "2.0.0"),
        ("", "2.0.0"),
        ("0.2.0", "0.2.0"),
        ("^0.2", "0.2.3"),
        ("^0.2.1", "0.2.3"),
        ("^0", "0.3.0"),
        ("^1", "1.4.2"),
        ("^1.2", "1.4.2"),
        ("~1.4", "1.4.2"),
        ("~0.2.1", "0.2.3"),
        ("~1", "1.4.2"),
        ("^3", None),
        ("9.9.9", None),
    ],
)
def test_select(spec, expected):
    assert select(VERSIONS, spec) == expected


def test_version_parse_and_order():
    assert Version.parse("1.2.3") < Version.parse("1.10.0")
    assert str(Version.parse("0.3.0")) == "0.3.0"
    assert is_at_least("0.2.0", "0.1.0") and not is_at_least("0.1.0", "0.2.0")
    with pytest.raises(ParameterError):
        Version.parse("1.2")
    with pytest.raises(ParameterError):
        matches(Version.parse("1.0.0"), "^x")


def test_split_artifact_spec():
    assert split_artifact_spec("nestjs-rest@^0.3") == ("nestjs-rest", "^0.3")
    assert split_artifact_spec("nestjs-rest") == ("nestjs-rest", "latest")
    with pytest.raises(ParameterError):
        split_artifact_spec("@1.0.0")


def test_index_roundtrip_and_errors():
    index = ArtifactsIndex.parse(
        '{"index_schema": 1, "generated_at": "t", "artifacts": {"a": {"kind": "project-template", '
        '"tag_prefix": "a-v", "latest": "0.2.0", "versions": {"0.1.0": {"url": "u", "sha256": "s"}, '
        '"0.2.0": {"url": "u2", "sha256": "s2"}}}}}'
    )
    assert index.artifacts["a"].resolve("^0.1") == "0.1.0"
    assert ArtifactsIndex.parse(index.dumps()) == index
    with pytest.raises(AdeCoreError):
        ArtifactsIndex.parse("{not json")
    with pytest.raises(AdeCoreError):
        ArtifactsIndex.parse('{"index_schema": 2, "generated_at": "t"}')


def _entry(output_dir: str, version: str = "0.1.0") -> ReceiptEntry:
    return ReceiptEntry(
        artifact="sample", version=version, source="path:x", output_dir=output_dir, generated_at="2026-11-27"
    )


def test_receipt_upsert_save_load(tmp_path):
    assert load_receipt(tmp_path) is None
    receipt = Receipt(engine_version="0.2.0")
    receipt.upsert(_entry("backend/a"))
    receipt.upsert(_entry("backend/b"))
    receipt.upsert(_entry("backend/a", "0.2.0"))
    assert [(e.output_dir, e.version) for e in receipt.artifacts] == [("backend/b", "0.1.0"), ("backend/a", "0.2.0")]
    path = save_receipt(tmp_path, receipt)
    assert path == receipt_path(tmp_path)
    assert path.read_text().startswith("# Generated by appdevexp")
    assert load_receipt(tmp_path) == receipt


def test_receipt_invalid(tmp_path):
    path = receipt_path(tmp_path)
    path.parent.mkdir()
    path.write_text("ade_receipt: 7\nengine_version: x\n")
    with pytest.raises(AdeCoreError):
        load_receipt(tmp_path)
